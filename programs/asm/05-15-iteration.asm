; Program 5.15: Root of x = f(x) by simple iteration, stopping at "machine zero"
;   (x(n+1) = x(n) to the last digit)
; Source: Дьяконов, «Справочник по расчётам на микрокалькуляторах», 1985, p.89 (book61.pdf page 90)
; The book's listing is a template: ПД, then the user's f(x) code ("..."), then
; ИПД ↔ ПД − Fx=0 01 ИПД С/П. Input: x0 in X. Output: root in X (also in Rd).
; This instance uses the book's example f(x) = sin x + 0,25 (code "ИПД Fsin ИП9 +",
; 0,25 = R9, given on p.88 for program 5.14), angle mode radians.
; NOTE: termination needs two successive iterates to be bit-identical; an emulator
; with binary doubles may stop later than the 8-digit calculator or cycle.
;
; Book example: x0 = 1,2 (from p.88) -> x = 1,1712298 (about 60 s)
; @angle rad
; @reg R9=0.25
; @input 1.2
; @expect X=1.1712298 tol=1e-6
;
; MK56-ASM form of 05-15-iteration.mk56, generated by mk56asm -s.
; Each comment gives the address, the keys as printed and the codes.

        STO RD          ; 00  Пd             4D

L01:
        RCL RD          ; 01  ИПd            6D
        SIN             ; 02  Fsin           1C
        RCL R9          ; 03  ИП9            69
        ADD             ; 04  +              10
        RCL RD          ; 05  ИПd            6D
        SWAP            ; 06  ↔              14
        STO RD          ; 07  Пd             4D
        SUB             ; 08  −              11
        JNZ L01         ; 09  Fx=0 01        5E 01
        RCL RD          ; 11  ИПd            6D
        HALT            ; 12  С/П            50
