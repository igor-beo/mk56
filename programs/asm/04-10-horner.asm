; Program 4.10: Real polynomial of degree n <= 11 by Horner's scheme
;   P(x) = a0 + a1 x + ... + an xⁿ = (...(an x + a(n-1))x + ... + a1)x + a0
; Source: Дьяконов, «Справочник по расчётам на микрокалькуляторах», 1985, p.65-66 (book61.pdf pages 66-67)
; Input: a0 = Rc, a1..an = R1..Rn (R10 = Ra, R11 = Rb), x in X. For a new x key
; only x and С/П.
; The book's listing is generic: steps 01-02 ("... ...") hold n as two digits
; (5 is keyed as 0 5) and step 04 is ИПn. This instance has n = 4 (01-02 = 0 4,
; 04 = ИП4).
;
; Book example: P(x) = 0 + 1x + 2x² + 3x³ + 4x⁴ (n = 4): P(1) = 10, P(2) = 98
; @reg Rc=0 R1=1 R2=2 R3=3 R4=4
; @input 1
; @expect X=10
; @input 2
; @expect X=98
;
; MK56-ASM form of 04-10-horner.mk56, generated by mk56asm -s.
; Each comment gives the address, the keys as printed and the codes.

L00:
        STO RD          ; 00  Пd             4D
        04              ; 01  0 4            00 04
        STO R0          ; 03  П0             40
        RCL R4          ; 04  ИП4            64
        ENTER           ; 05  В↑             0E

L06:
        SWAP            ; 06  ↔              14
        RCL RD          ; 07  ИПd            6D
        MUL             ; 08  ×              12
        RCL (R0)        ; 09  КИП0           D0
        ADD             ; 10  +              10
        RCL R0          ; 11  ИП0            60
        JNZ L06         ; 12  Fx=0 06        5E 06
        SWAP            ; 14  ↔              14
        RCL RC          ; 15  ИПc            6C
        ADD             ; 16  +              10
        HALT            ; 17  С/П            50
        JMP L00         ; 18  БП 00          51 00
