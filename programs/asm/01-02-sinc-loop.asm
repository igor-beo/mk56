; Chapter 1 example (unnumbered): y = sin(pi n f t)/(pi n f t), with y = 1 for t = 0;
; variant that needs only С/П for each new t
; Source: Дьяконов, «Справочник по расчётам на микрокалькуляторах», 1985, p.24 (book61.pdf page 25)
; Input: n in R8, f in R9, t in X.  Output: y in X.  Angle mode: radians.
; For each further t key t and С/П (БП 00 at 04/05, or БП 03 at 15/16 then С/П at 03).
;
; Book example (p.23): n = 2, f = 1000, t = 1,2*10^-4 -> y = 9,0790883*10^-1
; @angle rad
; @reg R8=2 R9=1000
; @input 0
; @expect X=1
; @input 1.2e-4
; @expect X=0.90790883 tol=1e-5
; @input 0
; @expect X=1
; @input 1.2e-4
; @expect X=0.90790883 tol=1e-5
;
; MK56-ASM form of 01-02-sinc-loop.mk56, generated by mk56asm -s.
; Each comment gives the address, the keys as printed and the codes.

L00:
        JNZ L06         ; 00  Fx=0 06        5E 06
        1               ; 02  1              01

L03:
        HALT            ; 03  С/П            50
        JMP L00         ; 04  БП 00          51 00

L06:
        PI              ; 06  Fπ             20
        RCL R8          ; 07  ИП8            68
        RCL R9          ; 08  ИП9            69
        MUL             ; 09  ×              12
        MUL             ; 10  ×              12
        MUL             ; 11  ×              12
        SIN             ; 12  Fsin           1C
        LASTX           ; 13  FBx            0F
        DIV             ; 14  ÷              13
        JMP L03         ; 15  БП 03          51 03
