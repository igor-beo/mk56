; Program 5.85: Uniform random numbers, multiplicative method V(n+1) = D(K·V(n)), K = 37
;   (D = fractional part; K = 8t ± 3 with t = 5)
; Source: Дьяконов, «Справочник по расчётам на микрокалькуляторах», 1985, p.138 (book61.pdf page 139)
; Input: V0 < 1 in Y (here: key V0, С/П; the first digit lifts it into Y).
; Output: each С/П gives the next V in X.
; "ПД КИПД XY ИПД −": КИПД cuts Rd = 37V+1 to its integer part (what КИПД
; loads is discarded), so 37V+1 − int(37V+1) = D(37V).
;
; Book example: V0 = 0,1234567 -> 0,5678979; 0,012222; 0,452214; 0,731918
; (exact to the last digit: the 8-digit truncation of 37V is part of the sequence)
; @input 0.1234567
; @expect X=0.5678979
; @run
; @expect X=0.012222
; @run
; @expect X=0.452214
; @run
; @expect X=0.731918
;
; MK56-ASM form of 05-85-random.mk56, generated by mk56asm -s.
; Each comment gives the address, the keys as printed and the codes.

L00:
        37              ; 00  3 7            03 07
        MUL             ; 02  ×              12
        1               ; 03  1              01
        ADD             ; 04  +              10
        STO RD          ; 05  Пd             4D
        RCL (RD)        ; 06  КИПd           DD
        SWAP            ; 07  ↔              14
        RCL RD          ; 08  ИПd            6D
        SUB             ; 09  −              11
        HALT            ; 10  С/П            50
        JMP L00         ; 11  БП 00          51 00
